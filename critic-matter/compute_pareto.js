/* Hover, tap, and keyboard details for the compute-versus-FID figure.
   Run data and point positions come from assets/compute_pareto_data.js (generated by build_assets.py). */
(() => {
  const data = window.COMPUTE_PARETO;
  const chart = document.querySelector('[data-chart="compute-pareto"]');
  if (!data || !chart) return;

  const layer = chart.querySelector('.chart-points');
  const tip = chart.querySelector('.chart-tooltip');
  const hint = chart.parentElement.querySelector('.chart-hint');
  // Snap radius around a marker, as a fraction of the chart width.
  const MOUSE_RADIUS = 0.022;
  const TOUCH_RADIUS = 0.05;
  // Below this chart width the details dock under the plot instead of floating over it.
  const DOCK_BELOW = 560;

  const make = (tag, className, text) => {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  };
  const params = (m) => `${m.toFixed(1)}M params`;
  // 1.2e-5 -> "1.2×10⁻⁵", 1e-6 -> "10⁻⁶" (as written in the paper).
  const SUPERSCRIPT = { '-': '⁻', 0: '⁰', 1: '¹', 2: '²', 3: '³', 4: '⁴', 5: '⁵', 6: '⁶', 7: '⁷', 8: '⁸', 9: '⁹' };
  const lr = (v) => {
    const [mantissa, exponent] = v.toExponential().split('e');
    const power = `10${[...String(Number(exponent))].map((ch) => SUPERSCRIPT[ch]).join('')}`;
    return mantissa === '1' ? power : `${mantissa}×${power}`;
  };

  const runs = [];
  data.panels.forEach((panel, i) => {
    const title = `(${'ab'[i]}) ${panel.student} student, ${panel.steps}-step`;
    for (const run of panel.runs) {
      const el = make('button', `chart-point${run.matched ? ' is-matched' : ''}`);
      el.type = 'button';
      el.tabIndex = -1;
      el.style.left = `${run.x * 100}%`;
      el.style.top = `${run.y * 100}%`;
      el.setAttribute('aria-label',
        `${title}, ${run.matched ? 'matched' : 'mismatched'} pair: teacher ${run.teacher}, critic ${run.critic}, ` +
        `best FID ${run.fid.toFixed(2)}, ${run.tflops.toFixed(1)} TFLOPs per student update, ` +
        `student learning rate ${run.student_lr.toExponential()}, critic learning rate ${run.critic_lr.toExponential()}`);
      layer.append(el);
      runs.push({ el, run, title });
    }
  });
  runs[0].el.tabIndex = 0;

  function fill({ run, title }) {
    const head = make('div', 'tt-head');
    head.append(make('span', `tt-mark${run.matched ? ' is-matched' : ''}`), make('span', '', run.matched ? 'Matched pair' : 'Mismatched pair'));
    const list = make('dl');
    const row = (term, value, extra) => {
      const dd = make('dd', '', value);
      if (extra) dd.append(make('span', 'tt-extra', extra));
      list.append(make('dt', '', term), dd);
    };
    row('Teacher', run.teacher, params(run.teacher_params_m));
    row('Critic', run.critic, params(run.critic_params_m));
    row('Best FID', run.fid.toFixed(2));
    row('TFLOPs per student update', run.tflops.toFixed(1));
    row('Student learning rate', lr(run.student_lr));
    row('Critic learning rate', lr(run.critic_lr));
    tip.replaceChildren(head, make('div', 'tt-sub', title), list);
  }

  function place({ run }) {
    const w = chart.clientWidth;
    const h = chart.clientHeight;
    const docked = w < DOCK_BELOW;
    tip.classList.toggle('is-docked', docked);
    if (docked) {
      tip.style.left = '0px';
      tip.style.top = `${h + 6}px`;
      return;
    }
    const px = run.x * w;
    const py = run.y * h;
    const gap = Math.max(10, 0.016 * w);
    tip.style.left = '0px';
    tip.style.top = '0px';
    const tw = tip.offsetWidth;
    const th = tip.offsetHeight;
    tip.style.left = `${Math.min(Math.max(px - tw / 2, 0), Math.max(w - tw, 0))}px`;
    tip.style.top = `${py - th - gap >= 0 ? py - th - gap : py + gap}px`;
  }

  let active = null;
  function show(entry) {
    if (entry === active) return;
    if (active) active.el.classList.remove('is-active');
    active = entry;
    if (!entry) {
      tip.hidden = true;
      return;
    }
    entry.el.classList.add('is-active');
    fill(entry);
    tip.hidden = false;
    place(entry);
  }

  function nearest(event, radius) {
    const box = chart.getBoundingClientRect();
    const mx = event.clientX - box.left;
    const my = event.clientY - box.top;
    let best = null;
    let bestDist = (radius * box.width) ** 2;
    for (const entry of runs) {
      const d = (entry.run.x * box.width - mx) ** 2 + (entry.run.y * box.height - my) ** 2;
      if (d <= bestDist) {
        best = entry;
        bestDist = d;
      }
    }
    return best;
  }

  chart.addEventListener('pointermove', (e) => {
    if (e.pointerType === 'mouse') show(nearest(e, MOUSE_RADIUS));
  });
  chart.addEventListener('pointerleave', (e) => {
    if (e.pointerType === 'mouse') show(null);
  });
  chart.addEventListener('pointerdown', (e) => {
    if (e.pointerType !== 'mouse') show(nearest(e, TOUCH_RADIUS));
  });
  document.addEventListener('pointerdown', (e) => {
    if (!chart.contains(e.target)) show(null);
  });

  // One tab stop for the whole figure; arrow keys step through runs in plotted order.
  layer.addEventListener('focusin', (e) => show(runs.find((r) => r.el === e.target) || null));
  layer.addEventListener('focusout', (e) => {
    if (!layer.contains(e.relatedTarget)) show(null);
  });
  layer.addEventListener('keydown', (e) => {
    const i = runs.findIndex((r) => r.el === document.activeElement);
    if (i < 0) return;
    const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
    let next = null;
    if (step) next = runs[(i + step + runs.length) % runs.length];
    else if (e.key === 'Home') next = runs[0];
    else if (e.key === 'End') next = runs[runs.length - 1];
    else if (e.key === 'Escape') {
      show(null);
      return;
    }
    if (!next) return;
    e.preventDefault();
    runs[i].el.tabIndex = -1;
    next.el.tabIndex = 0;
    next.el.focus();
  });

  window.addEventListener('resize', () => {
    if (active) place(active);
  });

  chart.classList.add('is-interactive');
  if (hint) hint.hidden = false;
})();
